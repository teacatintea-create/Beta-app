    private fun code(level: Int, r: Random): Draft {
        val d = domains.pick(r)
        val f = codeFeatures.pick(r)
        val algoIndex = r.nextInt(1000)
        return when (level) {
            1 -> if (r.nextBoolean()) Draft(
                "Модель данных: $d",
                "Опиши data class для предметной области «$d» (3–5 полей), создай список из 8–10 объектов и реализуй $f. Условие: ${codeConstraints1.pick(r)}.",
                "ООП", 25,
            ) else Draft(
                "Алгоритм: ${algos1[algoIndex % algos1.size].nom}",
                "Реализуй ${algos1[algoIndex % algos1.size].acc} на Kotlin. Сначала опиши идею словами, потом напиши код и проверь на трёх примерах, включая крайний случай.",
                "Алгоритмы", 20,
            )
            2 -> when (r.nextInt(3)) {
                0 -> Draft(
                    "Консольное приложение «$d»",
                    "Меню с командами: добавить, удалить, показать всё и $f. Условие: ${codeConstraints2.pick(r)}. Раздели код на небольшие функции.",
                    "Мини-проекты", 60,
                )
                1 -> Draft(
                    "Рефакторинг: $d",
                    "Напиши быстрое «грязное» решение для «$d» с функцией «$f», затем отрефактори его: выдели классы, убери дублирование. Условие: ${codeConstraints2.pick(r)}.",
                    "ООП", 50,
                )
                else -> Draft(
                    "Алгоритм: ${algos2[algoIndex % algos2.size].nom}",
                    "Реализуй ${algos2[algoIndex % algos2.size].acc}. Напиши тесты, оцени сложность по времени и памяти (O-нотация).",
                    "Алгоритмы", 45,
                )
            }
            else -> when (r.nextInt(3)) {
                0 -> Draft(
                    "Android-приложение «$d»",
                    "Приложение на Jetpack Compose: список, экран деталей, добавление записи и $f. Данные сохраняются между запусками. Условие: ${codeConstraints3.pick(r)}.",
                    "Android", 120,
                )
                1 -> Draft(
                    "Архитектура: $d",
                    "Спроектируй и напиши ядро сервиса «$d»: интерфейс репозитория, реализации в памяти и в файле, $f. Условия: ${codeConstraints3.pickDistinct(2, r).joinToString("; ")}.",
                    "Мини-проекты", 120,
                )
                else -> Draft(
                    "Алгоритм: ${algos3[algoIndex % algos3.size].nom}",
                    "Реализуй ${algos3[algoIndex % algos3.size].acc}. Визуализируй работу в консоли, покрой тестами и сравни производительность на больших данных.",
                    "Алгоритмы", 90,
                )
            }
        }
    }

