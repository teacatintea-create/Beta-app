/**
 * Процедурный генератор: собирает задания из шаблонов и списков слов.
 * Комбинаций тысячи, поэтому задания почти не повторяются.
 */
object TaskGenerator {

    fun generate(sphere: Sphere, difficulty: Difficulty, random: Random = Random.Default): PracticeTask {
        val draft = when (sphere) {
            Sphere.CODE -> code(difficulty.level, random)
            Sphere.MODEL3D -> modeling(difficulty.level, random)
            Sphere.ART2D -> art(difficulty.level, random)
        }
        val id = "gen-${sphere.id}-${difficulty.level}-" +
            Integer.toHexString((draft.title + draft.description).hashCode())
        return PracticeTask(
            id = id,
            sphere = sphere,
            title = draft.title,
            description = draft.description,
            difficulty = difficulty,
            topic = draft.topic,
            minutes = draft.minutes,
            source = TaskSource.GENERATOR,
        )
    }

    private class Draft(val title: String, val description: String, val topic: String, val minutes: Int)

    private fun <T> List<T>.pick(r: Random): T = this[r.nextInt(size)]

    /** Слова хранятся как «именительный|винительный» падеж, если формы различаются. */
    private val String.nom: String get() = substringBefore('|')
    private val String.acc: String get() = substringAfter('|')

    private fun List<String>.pickDistinct(n: Int, r: Random): List<String> = shuffled(r).take(n)

