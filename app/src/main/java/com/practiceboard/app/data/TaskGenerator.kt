                    "Основы", 30,
                )
            }
            2 -> if (r.nextInt(3) == 0) {
                val scene = scenes.pick(r)
                Draft(
                    "Мини-сцена: $scene",
                    "Собери небольшую сцену «$scene» в $style стиле: 3–5 ключевых объектов, освещение, финальный рендер. Условие: ${constraints3d2.pick(r)}.",
