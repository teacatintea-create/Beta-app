    val topics: List<LearningTopic> by lazy { codeTopics() + modelingTopics() + artTopics() }

    fun topics(sphere: Sphere): List<LearningTopic> = topics.filter { it.sphere == sphere }

    private class TopicBuilder(val sphere: Sphere, val prefix: String) {
        val list = mutableListOf<LearningTopic>()
        fun topic(level: Int, title: String, summary: String, points: List<String>, practice: String, taskTopic: String) {
            list += LearningTopic("$prefix${list.size + 1}", sphere, Difficulty.fromLevel(level), title, summary, points, practice, taskTopic)
        }
    }

    private fun build(sphere: Sphere, prefix: String, block: TopicBuilder.() -> Unit) =
        TopicBuilder(sphere, prefix).apply(block).list

